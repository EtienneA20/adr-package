import type { SidebarsConfig } from "@docusaurus/plugin-content-docs";

type Sidebar = SidebarsConfig[string];

/**
 * Barre latérale d'un package backend ou utilitaire : présentation, guides, puis référence API
 * générée par typedoc dans docs/<section>/api.
 */
function librarySidebar(section: "nest" | "misc"): Sidebar {
  return [
    `${section}/index`,
    { type: "autogenerated", dirName: `${section}/guides` },
    {
      type: "category",
      label: "Référence API",
      link: { type: "doc", id: `${section}/api/index` },
      items: [{ type: "autogenerated", dirName: `${section}/api` }],
    },
  ];
}

const sidebars: SidebarsConfig = {
  react: [{ type: "autogenerated", dirName: "react" }],
  nest: librarySidebar("nest"),
  misc: librarySidebar("misc"),
};

export default sidebars;
